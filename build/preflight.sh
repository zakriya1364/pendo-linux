#!/bin/bash
# Run BEFORE building. Needs no root. Stops at the first problem.
#   1. validates every Pendo kickstart with pykickstart (ksvalidator)
#   2. syntax-checks the %post / %pre scripts
#   3. on a Fedora host: confirms every package in %packages exists
set -euo pipefail
. "$(dirname "$0")/common.sh"
VER="F${PENDO_FEDORA}"
T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT

command -v ksvalidator >/dev/null || { echo "Install pykickstart first (dnf install pykickstart)"; exit 1; }

cp "$KSDIR"/pendo-*.ks "$T"/
# Stand-ins so ksvalidator can resolve includes that only exist at build time.
[ -f "$T/pendo-repo.ks" ] || cp "$KSDIR/pendo-repo.ks.example" "$T/pendo-repo.ks"
echo "# stub of Fedora base ks (real one is fetched by build-iso.sh)" > "$T/fedora-live-workstation.ks"

echo "== ksvalidator ($VER)"
( cd "$T"
  # pendo-install.ks includes a file generated by its own %pre at install time.
  echo zerombr > /tmp/pendo-part.ks
  for f in pendo-payload.ks pendo-install.ks; do ksvalidator -v "$VER" "$f"; done
  ksflatten -v "$VER" -c pendo-live.ks -o flat.ks && ksvalidator -v "$VER" flat.ks )

echo "== script syntax"
awk '/^%post/{f=1;next} /^%end/{f=0} f' "$T/pendo-payload.ks" > "$T/post.sh"; bash -n "$T/post.sh"
awk '/^%pre/{f=1;next} /^%end/{f=0} f' "$T/pendo-install.ks"  > "$T/pre.sh";  bash -n "$T/pre.sh"
for f in "$ROOT"/packages/pendo-defaults/root/usr/bin/* "$ROOT"/packages/pendo-defaults/root/usr/libexec/pendo/*; do bash -n "$f"; done
if command -v shellcheck >/dev/null; then shellcheck -s sh "$T/post.sh"; fi

echo "== package availability (Fedora $PENDO_FEDORA)"
if command -v dnf >/dev/null && [ -r /etc/fedora-release ]; then
  awk '/^%packages/{f=1;next} /^%end/{f=0} f && $1 !~ /^(#|-|@|$)/ {print $1}' "$T/pendo-payload.ks" | sort -u > "$T/pkgs"
  missing=0
  while read -r p; do
    [ "$p" = pendo-defaults ] && continue          # built locally by build-rpm.sh
    if ! dnf -q repoquery --releasever="$PENDO_FEDORA" --available --whatprovides "$p" 2>/dev/null | grep -q .; then
      echo "  MISSING: $p"; missing=1
    fi
  done < "$T/pkgs"
  [ "$missing" -eq 0 ] || { echo "Fix or remove the MISSING packages in pendo-payload.ks"; exit 1; }
  echo "  all packages found"
else
  echo "  SKIPPED: not a Fedora host with dnf. Run this on the Fedora build VM before building."
fi
echo "PREFLIGHT OK"
